// Generates the iOS `apple-touch-startup-image` set.
//
// iOS does not reliably use the web app manifest's `background_color` for the
// standalone launch surface; without a matching startup image it shows a blank
// (black) screen until the web view paints. These assets are the only way to
// brand that interval.
//
// Each image is the exact launch background for that appearance, so the handoff
// to the web launch screen is seamless: the background never changes, the mark
// and wordmark simply appear on top of it.
//
// The mark is deliberately NOT baked into these images. iOS requires PNG/JPEG at
// exact device pixel dimensions; the Sundial mark is a gradient illustration, so
// including it costs ~190 KB per image (~4.2 MB across the set) in PNG, and JPEG
// shifts the flat background by 1/255 — producing a visible seam at precisely
// the moment this is meant to be seamless. Background-only is 17 KB per image.
//
// Run: node scripts/generate-ios-startup-images.mjs
import { createCanvas } from "@napi-rs/canvas";
import fs from "node:fs";
import path from "node:path";

const OUT_DIR = path.join(process.cwd(), "public", "ios-launch");

// Must stay in sync with PWA_LAUNCH_VISUAL / PWA_LAUNCH_CRITICAL_CSS.
const BACKGROUND = { light: "#f8fafc", dark: "#101214" };

// Portrait-only: the manifest declares `orientation: "portrait"`. iOS only uses
// a startup image whose pixel dimensions match the device exactly, so each
// supported iPhone size needs its own asset. iPad is not covered.
const DEVICES = [
  { name: "iphone-se", w: 375, h: 667, dpr: 2 },
  { name: "iphone-8-plus", w: 414, h: 736, dpr: 3 },
  { name: "iphone-x", w: 375, h: 812, dpr: 3 },
  { name: "iphone-xr", w: 414, h: 896, dpr: 2 },
  { name: "iphone-xs-max", w: 414, h: 896, dpr: 3 },
  { name: "iphone-12", w: 390, h: 844, dpr: 3 },
  { name: "iphone-12-pro-max", w: 428, h: 926, dpr: 3 },
  { name: "iphone-14-pro", w: 393, h: 852, dpr: 3 },
  { name: "iphone-14-pro-max", w: 430, h: 932, dpr: 3 },
  { name: "iphone-16-pro", w: 402, h: 874, dpr: 3 },
  { name: "iphone-16-pro-max", w: 440, h: 956, dpr: 3 },
];

async function main() {
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const entries = [];
  let totalBytes = 0;

  for (const device of DEVICES) {
    for (const scheme of ["light", "dark"]) {
      const pxWidth = device.w * device.dpr;
      const pxHeight = device.h * device.dpr;
      const canvas = createCanvas(pxWidth, pxHeight);
      const ctx = canvas.getContext("2d");

      ctx.fillStyle = BACKGROUND[scheme];
      ctx.fillRect(0, 0, pxWidth, pxHeight);

      const file = `${device.name}-${scheme}.png`;
      const buffer = await canvas.encode("png");
      fs.writeFileSync(path.join(OUT_DIR, file), buffer);
      totalBytes += buffer.length;

      entries.push({
        href: `/ios-launch/${file}`,
        media: `(prefers-color-scheme: ${scheme}) and (device-width: ${device.w}px) and (device-height: ${device.h}px) and (-webkit-device-pixel-ratio: ${device.dpr}) and (orientation: portrait)`,
      });
    }
  }

  const manifestFile = path.join(
    process.cwd(),
    "src",
    "lib",
    "pwa",
    "iosStartupImages.generated.ts"
  );
  fs.writeFileSync(
    manifestFile,
    `// GENERATED by scripts/generate-ios-startup-images.mjs — do not edit by hand.\n` +
      `export type IosStartupImage = { href: string; media: string };\n\n` +
      `export const IOS_STARTUP_IMAGES: readonly IosStartupImage[] = ${JSON.stringify(
        entries,
        null,
        2
      )} as const;\n`,
    "utf8"
  );

  console.log(
    `wrote ${entries.length} startup images (${(totalBytes / 1024).toFixed(0)}KB total) + ${path.relative(process.cwd(), manifestFile)}`
  );
}

main();
